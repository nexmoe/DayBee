// Generate renderer defaults from the same Go contract as the native engine.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"github.com/nexmoe/DayBee/apps/desktop/internal/protocol"
)

func main() {
	defaults := protocol.DefaultSettingsForPlatform("recordings", "darwin")
	// Bootstrap supplies the native platform default. Keep the renderer's
	// pre-bootstrap fallback independent of the build machine's system model.
	defaults.Recording.ASRModel = protocol.ASRWhisperTiny
	settings, err := json.MarshalIndent(defaults, "", "  ")
	if err != nil {
		panic(err)
	}
	status, err := json.MarshalIndent(protocol.DefaultStatus(), "", "  ")
	if err != nil {
		panic(err)
	}
	content := fmt.Sprintf("// Code generated by cmd/contracts. DO NOT EDIT.\nimport type { AppSettings, RecorderStatusSnapshot } from \"../../../apps/desktop/src/renderer/src/generated/mygo\";\n\nexport const DEFAULT_SETTINGS: AppSettings = %s;\n\nexport const DEFAULT_STATUS: RecorderStatusSnapshot = %s;\n", settings, status)
	path := filepath.Join("..", "..", "packages", "shared", "src", "defaults.ts")
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		panic(err)
	}
}
