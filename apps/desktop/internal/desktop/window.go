package desktop

import (
	"os"
	"path/filepath"
	"runtime"
	"time"

	"github.com/egoist/mygo"
	"github.com/nexmoe/eve/apps/desktop/internal/config"
)

func (s *DesktopService) createWindow() error {
	options := mygo.WindowOptions{Title: AppName, URL: "/", Width: 420, Height: 620, MinWidth: 380, MinHeight: 480, MaxWidth: 520, Hidden: true}
	if s.test && os.Getenv("DAYBEE_TEST_VISUAL") == "1" {
		options.Page.PreloadScript = visualPreload
	}
	if runtime.GOOS == "darwin" {
		options.Frameless = true
		options.Transparent = true
		options.Vibrancy = mygo.VibrancyPopover
	} else {
		options.Frameless = true
		options.Vibrancy = mygo.VibrancyAcrylic
		options.BackgroundColor = "#ffffff"
	}
	window := mygo.NewWindow(options)
	s.window = window
	s.trackWindowUpdates("compact", window)
	installWindowCompatibility(window, 16)
	s.installPageRecovery("compact", window)
	if runtime.GOOS == "windows" {
		window.SetMenu(mygo.NewMenu(nil))
	}
	window.OnReadyToShow(func() { s.reveal() })
	window.OnClose(func(event *mygo.CloseEvent) {
		if !s.quitReady.Load() {
			event.PreventDefault()
			window.Hide()
		}
	})
	window.OnBlur(func() {
		if time.Now().UnixNano() < s.revealUntil.Load() {
			return
		}
		s.mu.RLock()
		pinned := s.pinned
		s.mu.RUnlock()
		if !pinned && !s.test && !s.quitting.Load() {
			window.Hide()
		}
	})
	window.OnResize(func() {
		width, height := window.Size()
		if s.store != nil {
			go s.store.SaveWindow(config.WindowState{Width: width, Height: height})
		}
	})
	resources, _ := mygo.App.Path(mygo.PathResources)
	icon, err := os.ReadFile(filepath.Join(resources, "icon.png"))
	if err != nil {
		return err
	}
	if runtime.GOOS == "darwin" {
		// This raster was generated by the original Electron nativeImage resize.
		icon, err = os.ReadFile(filepath.Join(resources, "tray-icon.png"))
		if err != nil {
			return err
		}
	}
	tray, err := mygo.NewTray(mygo.TrayOptions{Icon: icon, ToolTip: AppName + " 在后台待命"})
	if err != nil {
		return err
	}
	s.tray = tray
	tray.OnClick(func() {
		if window.IsVisible() && window.IsFocused() {
			window.Hide()
		} else {
			s.reveal()
		}
	})
	tray.OnRightClick(func() { tray.SetMenu(s.trayMenu()); tray.PopUpMenu(); tray.SetMenu(nil) })
	mygo.App.OnActivate(func(hasVisibleWindows bool) {
		if !hasVisibleWindows {
			s.reveal()
		}
	})
	return nil
}

func (s *DesktopService) reveal() {
	if s.backgroundTest() {
		return
	}
	window := s.window
	if window == nil {
		return
	}
	s.revealUntil.Store(time.Now().Add(200 * time.Millisecond).UnixNano())
	if window.IsMinimized() {
		window.Restore()
	}
	if runtime.GOOS == "windows" {
		window.Center()
	} else {
		if mygo.App.IsHidden() {
			mygo.App.Show()
		}
		window.SetVisibleOnAllWorkspaces(true)
		width, _ := window.Size()
		display := mygo.Screen.PrimaryDisplay()
		bounds := mygo.Rectangle{}
		if s.tray != nil {
			bounds = s.tray.Bounds()
		}
		if bounds.Width > 0 {
			x := bounds.X + bounds.Width/2 - width/2
			x = max(display.WorkArea.X+8, min(x, display.WorkArea.X+display.WorkArea.Width-width-8))
			window.SetPosition(x, bounds.Y+bounds.Height+4)
		} else {
			window.SetPosition(display.WorkArea.X+display.WorkArea.Width-width-12, 4)
		}
	}
	window.Show()
	window.Focus()
	window.SetVisibleOnAllWorkspaces(false)
}

func (s *DesktopService) backgroundTest() bool {
	return s.test && os.Getenv("DAYBEE_TEST_BACKGROUND") == "1"
}
